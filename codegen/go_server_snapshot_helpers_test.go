func TestRuntimeLoadSnapshotIfExistsRestoresGeneratedEntity(t *testing.T) {
	path := filepath.Join(t.TempDir(), "world.snap")
	src, rt := NewServer(golem.ServerConfig{})
	ent := &SyncedProbe{token: 0x42}
	if err := src.CreateEntity(ent); err != nil {
		t.Fatalf("CreateEntity: %v", err)
	}
	id := ent.EntityID()
	if id == 0 {
		t.Fatal("CreateEntity left EntityID=0")
	}
	if err := <-rt.SaveSnapshot(path); err != nil {
		t.Fatalf("SaveSnapshot: %v", err)
	}

	dst, rt2 := NewServer(golem.ServerConfig{})
	ok, err := rt2.LoadSnapshotIfExists(path)
	if err != nil || !ok {
		t.Fatalf("LoadSnapshotIfExists: ok=%v err=%v", ok, err)
	}
	got, found := dst.Get(id)
	if !found {
		t.Fatalf("restored entity id=%d missing (unknown-type skip would also fail here)", id)
	}
	probe, ok := got.(*SyncedProbe)
	if !ok {
		t.Fatalf("restored type = %T, want *SyncedProbe", got)
	}
	if probe.token != 0x42 {
		t.Fatalf("restored token = %#x, want 0x42", probe.token)
	}
}
