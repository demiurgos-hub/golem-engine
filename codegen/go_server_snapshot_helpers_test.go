func TestRunSnapshotAutosaveSerializedSaves(t *testing.T) {
	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()

	ticks := make(chan time.Time)
	release := make(chan struct{})
	var started atomic.Int32
	var maxStarted atomic.Int32

	save := func() <-chan error {
		errc := make(chan error, 1)
		cur := started.Add(1)
		for {
			old := maxStarted.Load()
			if cur <= old || maxStarted.CompareAndSwap(old, cur) {
				break
			}
		}
		go func() {
			<-release
			started.Add(-1)
			errc <- nil
		}()
		return errc
	}

	done := make(chan error, 1)
	go func() { done <- runSnapshotAutosave(ctx, ticks, save) }()

	ticks <- time.Time{}
	secondTickAccepted := make(chan struct{})
	go func() {
		ticks <- time.Time{}
		close(secondTickAccepted)
	}()

	select {
	case <-secondTickAccepted:
		t.Fatal("second tick accepted while first save still in flight")
	default:
	}
	if got := started.Load(); got != 1 {
		t.Fatalf("in-flight saves = %d, want 1", got)
	}

	release <- struct{}{}
	<-secondTickAccepted
	release <- struct{}{}
	cancel()
	if err := <-done; !errors.Is(err, context.Canceled) {
		t.Fatalf("error = %v, want context.Canceled", err)
	}
	if got := maxStarted.Load(); got != 1 {
		t.Fatalf("max concurrent saves = %d, want 1", got)
	}
}

