// TestGenerateGoSharedTemplateSnapshotHelpersBehavior builds a temporary module
// from shared.go.tmpl and runs behavior tests for LoadSnapshotIfExists and
// RunSnapshotAutosave against real golem.Server snapshot APIs.
func TestGenerateGoSharedTemplateSnapshotHelpersBehavior(t *testing.T) {
	tmpl, err := loadEmbeddedTemplate("templates/go_server/shared.go.tmpl")
	if err != nil {
		t.Fatalf("loadEmbeddedTemplate: %v", err)
	}

	data := schema.SharedData{
		GolemImport: "github.com/demiurgos-hub/golem-engine/golem",
		GoPackage:   "snapruntimetest",
		Fingerprint: "unit5-fingerprint",
		Entities:    []schema.EntityData{{Name: "Probe"}},
	}
	var generated bytes.Buffer
	if err := tmpl.Execute(&generated, data); err != nil {
		t.Fatalf("Execute: %v", err)
	}

	repoRoot, err := os.Getwd()
	if err != nil {
		t.Fatalf("Getwd: %v", err)
	}
	// codegen tests run with cwd = codegen/; repo root is the parent.
	repoRoot = filepath.Clean(filepath.Join(repoRoot, ".."))
	repoRootSlash := filepath.ToSlash(repoRoot)

	dir := t.TempDir()
	write := func(name, content string) {
		t.Helper()
		path := filepath.Join(dir, name)
		if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
			t.Fatalf("WriteFile %s: %v", name, err)
		}
	}

	write("go.mod", strings.ReplaceAll(`module snapruntimetest

go 1.25.4

require github.com/demiurgos-hub/golem-engine v0.0.0

replace github.com/demiurgos-hub/golem-engine => REPO

replace github.com/demiurgos-hub/golem-engine/golem/collision => REPO/golem/collision

replace github.com/demiurgos-hub/golem-engine/golem/nav => REPO/golem/nav
`, "REPO", repoRootSlash))
	write("golem_helpers.go", generated.String())
	write("stubs.go", snapshotHelperStubs)
	write("helpers_test.go", snapshotHelperBehaviorTests)

	env := []string{"GOWORK=off"}
	for _, kv := range os.Environ() {
		if strings.HasPrefix(kv, "GOWORK=") {
			continue
		}
		env = append(env, kv)
	}
	tidy := exec.Command("go", "mod", "tidy")
	tidy.Dir = dir
	tidy.Env = env
	if out, err := tidy.CombinedOutput(); err != nil {
		t.Fatalf("go mod tidy in generated harness failed: %v\n%s", err, out)
	}
	cmd := exec.Command("go", "test", "-count=1", ".")
	cmd.Dir = dir
	cmd.Env = env
	out, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("go test in generated harness failed: %v\n%s", err, out)
	}
}

