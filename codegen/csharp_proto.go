	writeCSharpFooter(&b, namespace)
	outPath := filepath.Join(outDir, "EventsPb.cs")
	if err := os.WriteFile(outPath, []byte(b.String()), 0o644); err != nil {
		return err
	}
	fmt.Printf("  wrote %s\n", outPath)
