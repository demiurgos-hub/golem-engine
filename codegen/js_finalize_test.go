func TestIsGeneratedJSIntermediateTS(t *testing.T) {
	wantRemove := []string{
		"EntityManager.ts",
		"EventManager.ts",
		"WorldManager.ts",
		"entities_pb.ts",
		"events_pb.ts",
		"world_pb.ts",
		"client.ts",
		"PlayerSynced.ts",
		"BattleViewSynced.ts",
		"NpcSynced.ts",
	}
	for _, name := range wantRemove {
		if !isGeneratedJSIntermediateName(name) {
			t.Fatalf("%s: want generated intermediate", name)
		}
	}

	wantKeep := []string{
		"helpers.ts",               // authored / unknown
		"custom_utils.ts",          // authored / unknown
		"PlayerSynced.d.ts",        // declaration output
		"entities_pb.d.ts",         // declaration output
		"client.js",                // not .ts
		"tsconfig.golem-bake.json", // handled separately
	}
	for _, name := range wantKeep {
		if isGeneratedJSIntermediateName(name) {
			t.Fatalf("%s: must not be treated as generated intermediate", name)
		}
	}
}

func TestRemoveGeneratedJSIntermediates(t *testing.T) {
	dir := t.TempDir()
	files := map[string]string{
		"EntityManager.ts":         "export {}",
		"EventManager.ts":          "export {}",
		"WorldManager.ts":          "export {}",
		"entities_pb.ts":           "export {}",
		"events_pb.ts":             "export {}",
		"world_pb.ts":              "export {}",
		"client.ts":                "export {}",
		"PlayerSynced.ts":          "export {}",
		"helpers.ts":               "export const authored = 1;",
		"PlayerSynced.d.ts":        "export {}",
		"entities_pb.d.ts":         "export {}",
		"client.js":                "export {}",
		"tsconfig.golem-bake.json": "{}",
	}
	for name, body := range files {
		if err := os.WriteFile(filepath.Join(dir, name), []byte("// GENERATED by Golem Engine \u2014 do not edit.\n"+body), 0o644); err != nil {
			t.Fatalf("write %s: %v", name, err)
		}
	}

	if err := removeGeneratedJSIntermediates(dir); err != nil {
		t.Fatalf("removeGeneratedJSIntermediates: %v", err)
	}

	mustGone := []string{
		"EntityManager.ts", "EventManager.ts", "WorldManager.ts",
		"entities_pb.ts", "events_pb.ts", "world_pb.ts",
		"client.ts", "PlayerSynced.ts", "tsconfig.golem-bake.json",
	}
	for _, name := range mustGone {
		if _, err := os.Stat(filepath.Join(dir, name)); !os.IsNotExist(err) {
			t.Fatalf("%s: want removed, err=%v", name, err)
		}
	}

	mustRemain := []string{"helpers.ts", "PlayerSynced.d.ts", "entities_pb.d.ts", "client.js"}
	for _, name := range mustRemain {
		if _, err := os.Stat(filepath.Join(dir, name)); err != nil {
			t.Fatalf("%s: want kept: %v", name, err)
		}
	}
}

func TestCleanupRequiresOwnership(t *testing.T) {
	for _, name := range []string{"OldSynced.ts", "EventManager.ts", "WorldManager.ts", "events_pb.ts", "client.ts"} {
		t.Run(name, func(t *testing.T) {
			dir := t.TempDir()
			file := filepath.Join(dir, name)
			body := []byte("export const authored = true;")
			if err := os.WriteFile(file, body, 0600); err != nil {
				t.Fatal(err)
			}
			if err := removeGeneratedJSIntermediates(dir); err != nil {
				t.Fatal(err)
			}
			if got, err := os.ReadFile(file); err != nil || string(got) != string(body) {
				t.Fatalf("authored file changed: %q %v", got, err)
			}
			if err := os.WriteFile(file, []byte("// GENERATED by Golem Engine - do not edit.\n"), 0600); err != nil {
				t.Fatal(err)
			}
			if err := removeGeneratedJSIntermediates(dir); err != nil {
				t.Fatal(err)
			}
			if _, err := os.Stat(file); !os.IsNotExist(err) {
				t.Fatalf("historical output remains: %v", err)
			}
		})
	}
}

func TestCleanupKeepsNonregularAndNestedFiles(t *testing.T) {
	dir := t.TempDir()
	nested := filepath.Join(dir, "NestedSynced.ts")
	if err := os.Mkdir(nested, 0700); err != nil {
		t.Fatal(err)
	}
	file := filepath.Join(nested, "EntityManager.ts")
	if err := os.WriteFile(file, []byte("// GENERATED by Golem Engine"), 0600); err != nil {
		t.Fatal(err)
	}
	if err := removeGeneratedJSIntermediates(dir); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(file); err != nil {
		t.Fatal(err)
	}
	target := filepath.Join(t.TempDir(), "generated.ts")
	if err := os.WriteFile(target, []byte("// GENERATED by Golem Engine"), 0600); err != nil {
		t.Fatal(err)
	}
	link := filepath.Join(dir, "OldSynced.ts")
	if err := os.Symlink(target, link); err != nil {
		t.Skipf("symlinks unavailable: %v", err)
	}
	if err := removeGeneratedJSIntermediates(dir); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Lstat(link); err != nil {
		t.Fatal(err)
	}
}

func TestCompileJSCleansOnlyAfterSuccess(t *testing.T) {
	root, err := filepath.Abs("../golem-js")
	if err != nil {
		t.Fatal(err)
	}
	for _, requirement := range []string{filepath.Join(root, "node_modules/typescript/lib/tsc.js")} {
		if _, err := os.Stat(requirement); err != nil {
			if os.Getenv("GOLEM_REQUIRE_CONSUMERS") == "1" {
				t.Fatal(err)
			}
			t.Skip("install golem-js dependencies")
		}
	}
	if _, err := exec.LookPath("node"); err != nil {
		if os.Getenv("GOLEM_REQUIRE_CONSUMERS") == "1" {
			t.Fatal(err)
		}
		t.Skip("Node.js required")
	}
	out := t.TempDir()
	writeConsumerFile(t, out, "EntityManager.ts", "// GENERATED by Golem Engine - do not edit.\nexport const broken: number = 'bad';")
	writeConsumerFile(t, out, "EventManager.ts", "export const authored = true;")
	writeConsumerFile(t, out, "nested/OldSynced.ts", "// GENERATED by Golem Engine - do not edit.\nexport const nested = true;")
	err = compileJSIntegration(root, out)
	if err == nil || !strings.Contains(err.Error(), "tsc in ") {
		t.Fatalf("expected compiler diagnostic: %v", err)
	}
	for _, file := range []string{"EntityManager.ts", "EventManager.ts", "tsconfig.golem-bake.json"} {
		if _, err := os.Stat(filepath.Join(out, file)); err != nil {
			t.Fatal("failed compile removed diagnostic input", err)
		}
	}
	writeConsumerFile(t, out, "EntityManager.ts", "// GENERATED by Golem Engine - do not edit.\nexport const valid = true;")
	if err := compileJSIntegration(root, out); err != nil {
		t.Fatal(err)
	}
	for _, file := range []string{"EntityManager.ts", "tsconfig.golem-bake.json"} {
		if _, err := os.Stat(filepath.Join(out, file)); !os.IsNotExist(err) {
			t.Fatalf("retained intermediate %s: %v", file, err)
		}
	}
	for _, file := range []string{"EntityManager.js", "EntityManager.d.ts", "EventManager.ts", "EventManager.js", "EventManager.d.ts", "nested/OldSynced.ts", "nested/OldSynced.js", "nested/OldSynced.d.ts"} {
		if _, err := os.Stat(filepath.Join(out, file)); err != nil {
			t.Fatalf("missing preserved or recursively compiled output %s: %v", file, err)
		}
	}
}
