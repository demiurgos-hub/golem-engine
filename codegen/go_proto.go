// writeGoCustomTypeStruct emits the struct definition plus Marshal/Unmarshal for one custom type.
func writeGoCustomTypeStruct(b *strings.Builder, ct schema.CustomTypeData) {
	w := func(f string, a ...any) { fmt.Fprintf(b, f+"\n", a...) }

	w("")
	w("// %s is a custom composite type.", ct.Name)
	w("type %s struct {", ct.Name)
	for _, f := range ct.Fields {
		w("\t%s %s", f.GoName, f.GoType)
	}
	w("}")

	w("")
	w("// Marshal encodes %s to protobuf wire format.", ct.Name)
	w("func (m *%s) Marshal() []byte {", ct.Name)
	w("\tw := &pb.Writer{}")
	for _, f := range ct.Fields {
		writeGoFieldEncode(b, f.GoName, f.ProtoType, f.ProtoTag, false)
	}
	w("\treturn w.Finish()")
	w("}")

	w("")
	w("// Unmarshal decodes %s from protobuf wire format.", ct.Name)
	w("func (m *%s) Unmarshal(data []byte) (retErr error) {", ct.Name)
	w("\tdefer func() { if r := recover(); r != nil { retErr = fmt.Errorf(\"pb: decode %s: %%v\", r) } }()", ct.Name)
	w("\trd := pb.NewReader(data)")
	w("\tfor !rd.Done() {")
	w("\t\tfield, wire := rd.Tag()")
	w("\t\tswitch field {")
	for _, f := range ct.Fields {
		w("\t\tcase %d: m.%s = rd.%s()", f.ProtoTag, f.GoName, goWriterMethod[f.ProtoType])
	}
	w("\t\tdefault: rd.Skip(wire)")
	w("\t\t}")
	w("\t}")
	w("\treturn nil")
	w("}")
}

// writeGoCollectionMarshal emits the marshal code for a list or map field.
// optional=true skips encoding when the field is nil (used for delta fields).
func writeGoCollectionMarshal(b *strings.Builder, v goCollectionField, tag int, optional bool) {
	w := func(f string, a ...any) { fmt.Fprintf(b, f+"\n", a...) }

	if v.IsRepeated {
		if optional {
			w("\tif m.%s != nil {", v.GoName)
			w("\t\tif len(m.%s) == 0 {", v.GoName)
			w("\t\t\tw.Tag(%d, 2).Bytes(nil)", tag)
			w("\t\t} else {")
			w("\t\t\tfor _, _elem := range m.%s {", v.GoName)
			emitGoCollectionElemMarshal(b, v, tag, "\t\t\t\t")
			w("\t\t\t}")
			w("\t\t}")
			w("\t}")
		} else {
			w("\tfor _, _elem := range m.%s {", v.GoName)
			emitGoCollectionElemMarshal(b, v, tag, "\t\t")
			w("\t}")
		}
	} else { // IsMap
		if optional {
			w("\tif m.%s != nil {", v.GoName)
			w("\t\tif len(m.%s) == 0 {", v.GoName)
			w("\t\t\tw.Tag(%d, 2).Bytes(nil)", tag)
			w("\t\t} else {")
			w("\t\t\tfor _k, _v := range m.%s {", v.GoName)
			emitGoMapEntryMarshal(b, v, tag, "\t\t\t\t")
			w("\t\t\t}")
			w("\t\t}")
			w("\t}")
		} else {
			w("\tfor _k, _v := range m.%s {", v.GoName)
			emitGoMapEntryMarshal(b, v, tag, "\t\t")
			w("\t}")
		}
	}
}

// emitGoCollectionElemMarshal emits the single-element encode call for a list field.
func emitGoCollectionElemMarshal(b *strings.Builder, v goCollectionField, tag int, indent string) {
	if v.ElemIsCustom {
		fmt.Fprintf(b, indent+"w.Tag(%d, 2).Bytes(_elem.Marshal())\n", tag)
	} else {
		// Encode scalar in a sub-writer so all list elements use wire type 2 uniformly.
		fmt.Fprintf(b, "{ _inner := &pb.Writer{}; _inner.%s(_elem); w.Tag(%d, 2).Bytes(_inner.Finish()) }\n",
			goWriterMethod[v.ElemProtoType], tag)
	}
}

// emitGoMapEntryMarshal emits the K/V sub-message encode call for one map entry.
func emitGoMapEntryMarshal(b *strings.Builder, v goCollectionField, tag int, indent string) {
	w := func(f string, a ...any) { fmt.Fprintf(b, indent+f+"\n", a...) }
	keyWT := scalarWireType(v.MapKeyProtoType)
	keyWM := goWriterMethod[v.MapKeyProtoType]
	w("_kv := &pb.Writer{}")
	w("_kv.Tag(1, %d).%s(_k)", keyWT, keyWM)
	if v.ElemIsCustom {
		w("_kv.Tag(2, 2).Bytes(_v.Marshal())")
	} else {
		valWT := scalarWireType(v.ElemProtoType)
		valWM := goWriterMethod[v.ElemProtoType]
		w("_kv.Tag(2, %d).%s(_v)", valWT, valWM)
	}
	w("w.Tag(%d, 2).Bytes(_kv.Finish())", tag)
}

// writeGoCollectionUnmarshal emits the case + decode logic for a list or map field.
// optional=true initializes nil collections on first appearance (used for delta fields).
func writeGoCollectionUnmarshal(b *strings.Builder, v goCollectionField, tag int, optional bool) {
	w := func(f string, a ...any) { fmt.Fprintf(b, f+"\n", a...) }

	w("\t\tcase %d:", tag)
	if v.IsRepeated {
		if optional {
			w("\t\t\tif m.%s == nil { m.%s = %s{} }", v.GoName, v.GoName, v.GoType)
		}
		w("\t\t\t_b := rd.Bytes()")
		w("\t\t\tif len(_b) > 0 {")
		emitGoCollectionElemUnmarshal(b, v, "\t\t\t\t")
		w("\t\t\t}")
	} else { // IsMap
		w("\t\t\t_b := rd.Bytes()")
		w("\t\t\tif len(_b) > 0 {")
		emitGoMapEntryUnmarshal(b, v, "\t\t\t\t")
		w("\t\t\t} else {")
		w("\t\t\t\tif m.%s == nil { m.%s = %s{} }", v.GoName, v.GoName, v.GoType)
		w("\t\t\t}")
	}
}

// emitGoCollectionElemUnmarshal emits the decode + append for one list element.
func emitGoCollectionElemUnmarshal(b *strings.Builder, v goCollectionField, indent string) {
	w := func(f string, a ...any) { fmt.Fprintf(b, indent+f+"\n", a...) }
	if v.ElemIsCustom {
		w("var _elem %s", v.ElemProtoType)
		w("if _err := _elem.Unmarshal(_b); _err != nil { return _err }")
		w("m.%s = append(m.%s, _elem)", v.GoName, v.GoName)
	} else {
		w("_inner := pb.NewReader(_b)")
		w("m.%s = append(m.%s, _inner.%s())", v.GoName, v.GoName, goWriterMethod[v.ElemProtoType])
	}
}

// emitGoMapEntryUnmarshal emits the K/V sub-message decode + assignment for one map entry.
func emitGoMapEntryUnmarshal(b *strings.Builder, v goCollectionField, indent string) {
	w := func(f string, a ...any) { fmt.Fprintf(b, indent+f+"\n", a...) }
	w("_rd := pb.NewReader(_b)")
	w("var _k %s", v.MapKeyGoType)
	w("var _v %s", v.ElemGoType)
	w("for !_rd.Done() {")
	w("\t_f, _ := _rd.Tag()")
	w("\tswitch _f {")
	w("\tcase 1: _k = _rd.%s()", goWriterMethod[v.MapKeyProtoType])
	if v.ElemIsCustom {
		w("\tcase 2:")
		w("\t\tif _err := _v.Unmarshal(_rd.Bytes()); _err != nil { return _err }")
	} else {
		w("\tcase 2: _v = _rd.%s()", goWriterMethod[v.ElemProtoType])
	}
	w("\t}")
	w("}")
	w("if m.%s == nil { m.%s = %s{} }", v.GoName, v.GoName, v.GoType)
	w("m.%s[_k] = _v", v.GoName)
}

// writeGoFieldEncode emits a single field encode line for a required or optional field.
func writeGoFieldEncode(b *strings.Builder, goName, protoType string, tag int, optional bool) {
	w := func(f string, a ...any) { fmt.Fprintf(b, f+"\n", a...) }
	wt := scalarWireType(protoType)
	wm := goWriterMethod[protoType]

	if optional {
		w("\tif m.%s != nil { w.Tag(%d, %d).%s(*m.%s) }", goName, tag, wt, wm, goName)
		return
	}

	switch protoType {
	case "bool":
		w("\tif m.%s { w.Tag(%d, %d).%s(m.%s) }", goName, tag, wt, wm, goName)
	case "bytes":
		w("\tif len(m.%s) > 0 { w.Tag(%d, %d).%s(m.%s) }", goName, tag, wt, wm, goName)
	default:
		zero := goZeroExpr[protoType]
		w("\tif m.%s != %s { w.Tag(%d, %d).%s(m.%s) }", goName, zero, tag, wt, wm, goName)
	}
}
