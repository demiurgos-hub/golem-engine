// --- EntityRemoved ---

func writeGoEntityRemoved(b *strings.Builder) {
	w := func(f string, a ...any) { fmt.Fprintf(b, f+"\n", a...) }

	w("")
	w("type EntityRemoved struct {")
	w("\tEntityId int64")
	w("\tRevision uint64")
	w("}")
	w("")
	w("// Marshal encodes the removal marker to protobuf wire format.")
	w("func (m *EntityRemoved) Marshal() []byte {")
	w("\tw := &pb.Writer{}")
	w("\tif m.EntityId != 0 { w.Tag(1, 0).Int64(m.EntityId) }")
	w("\tif m.Revision != 0 { w.Tag(%d, 0).Uint64(m.Revision) }", entityRevisionProtoTag)
	w("\treturn w.Finish()")
	w("}")
	w("")
	w("// Unmarshal decodes the removal marker from protobuf wire format.")
	w("func (m *EntityRemoved) Unmarshal(data []byte) (retErr error) {")
	w("\tdefer func() { if r := recover(); r != nil { retErr = fmt.Errorf(\"pb: decode EntityRemoved: %%v\", r) } }()")
	w("\trd := pb.NewReader(data)")
	w("\tfor !rd.Done() {")
	w("\t\tfield, wire := rd.Tag()")
	w("\t\tswitch field {")
	w("\t\tcase 1: m.EntityId = rd.Int64()")
	w("\t\tcase %d: m.Revision = rd.Uint64()", entityRevisionProtoTag)
	w("\t\tdefault: rd.Skip(wire)")
	w("\t\t}")
	w("\t}")
	w("\treturn nil")
	w("}")
}

