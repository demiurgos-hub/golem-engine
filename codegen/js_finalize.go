package codegen

import (
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
)

const jsBakeTSConfig = `{
  "compilerOptions": {
    "target": "ES2020",
    "module": "ESNext",
    "moduleResolution": "bundler",
    "declaration": true,
    "strict": true,
    "skipLibCheck": true
  },
  "include": ["./**/*.ts"]
}
`

// removeGeneratedJSIntermediates deletes marked, regular bake intermediate .ts files and
// the temporary bake tsconfig from outDir. Unknown/authored .ts and .d.ts survive.
func removeGeneratedJSIntermediates(outDir string) error {
	entries, err := os.ReadDir(outDir)
	if err != nil {
		return fmt.Errorf("read %s: %w", outDir, err)
	}
	for _, e := range entries {
		if e.IsDir() {
			continue
		}
		name := e.Name()
		if name == "tsconfig.golem-bake.json" {
			_ = os.Remove(filepath.Join(outDir, name))
			continue
		}
		if isGeneratedJSIntermediateName(name) {
			path := filepath.Join(outDir, name)
			info, err := os.Lstat(path)
			if err != nil || !info.Mode().IsRegular() {
				continue
			}
			contents, err := os.ReadFile(path)
			if err != nil || !strings.HasPrefix(string(contents), "// GENERATED by Golem Engine") {
				continue
			}
			_ = os.Remove(path)
		}
	}
	return nil
}

// compileJSIntegration recursively compiles TypeScript in outDir, then removes
// marked top-level intermediates and the temporary compiler config on success.
func compileJSIntegration(projectRoot, outDir string) error {
	cfgPath := filepath.Join(outDir, "tsconfig.golem-bake.json")
	if err := os.WriteFile(cfgPath, []byte(jsBakeTSConfig), 0o644); err != nil {
		return fmt.Errorf("write tsconfig.golem-bake.json: %w", err)
	}

	tscJS := filepath.Join(projectRoot, "node_modules", "typescript", "lib", "tsc.js")
	var cmd *exec.Cmd
	if _, err := os.Stat(tscJS); err == nil {
		node, err := exec.LookPath("node")
		if err != nil {
			return fmt.Errorf("js-client integration: need Node.js to run TypeScript compiler: %w", err)
		}
		cmd = exec.Command(node, tscJS, "-p", cfgPath)
	} else {
		tscBin, err := exec.LookPath("tsc")
		if err != nil {
			return fmt.Errorf("js-client integration: install devDependency \"typescript\" in your project root, or put \"tsc\" on PATH")
		}
		cmd = exec.Command(tscBin, "-p", cfgPath)
	}
	cmd.Dir = outDir
	out, err := cmd.CombinedOutput()
	if err != nil {
		return fmt.Errorf("tsc in %s: %w\n%s", outDir, err, out)
	}

	if err := removeGeneratedJSIntermediates(outDir); err != nil {
		return err
	}
	return nil
}
