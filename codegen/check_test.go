const checkFixtureConfig = `entity_schema: entities
types_schema: types
simulation:
  dimensions: 3
proto:
  package: fixture
  out: proto/entities.proto
integrations:
  go-server:
    out: generated
    package: generated
  csharp-client:
    out: csharp
    package: Fixture.Generated
  unity:
    out: csharp
    package: Fixture.Generated
`

// checkFixture bakes a small project whose csharp-client and unity outputs
// share one directory, so orphan detection must use the union of both.
func checkFixture(t *testing.T) string {
	t.Helper()
	dir := t.TempDir()
	writeConsumerFile(t, dir, "golem.yaml", checkFixtureConfig)
	writeConsumerFile(t, dir, "entities/actor.yaml", "entity: Actor\nvars:\n  hp: {tag: 1, type: int32, sync: tick}\n  bag: {tag: 2, type: list<Item>, sync: tick}\n")
	writeConsumerFile(t, dir, "types/item.yaml", "type: Item\nfields:\n  name: {tag: 1, type: string}\n")
	if err := Bake(dir); err != nil {
		t.Fatal(err)
	}
	return dir
}

// treeHash records every path under dir with its content hash, or "dir".
func treeHash(t *testing.T, dir string) map[string]string {
	t.Helper()
	tree := map[string]string{}
	err := filepath.WalkDir(dir, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, _ := filepath.Rel(dir, path)
		if d.IsDir() {
			tree[rel] = "dir"
			return nil
		}
		b, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		sum := sha256.Sum256(b)
		tree[rel] = hex.EncodeToString(sum[:])
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	return tree
}

// checkUnchanged runs Check and fails if the project tree changed in any way.
func checkUnchanged(t *testing.T, dir string) (CheckResult, error) {
	t.Helper()
	before := treeHash(t, dir)
	result, err := Check(dir)
	if after := treeHash(t, dir); !reflect.DeepEqual(before, after) {
		t.Fatalf("Check modified the project:\nbefore %v\nafter  %v", before, after)
	}
	return result, err
}

func isolateTemp(t *testing.T) string {
	t.Helper()
	tmp := t.TempDir()
	for _, key := range []string{"TMPDIR", "TMP", "TEMP"} {
		t.Setenv(key, tmp)
	}
	return tmp
}

func requireEmptyDir(t *testing.T, dir string) {
	t.Helper()
	entries, err := os.ReadDir(dir)
	if err != nil {
		t.Fatal(err)
	}
	for _, entry := range entries {
		// Node's own persistent compile cache (enabled by TypeScript's tsc.js
		// shim); a normal bake creates it too.
		if entry.Name() == "node-compile-cache" {
			continue
		}
		t.Fatalf("Check left temporary files: %v", entries)
	}
}

func TestCheckAfterBakeIsUpToDate(t *testing.T) {
	dir := checkFixture(t)
	tmp := isolateTemp(t)
	result, err := checkUnchanged(t, dir)
	if err != nil {
		t.Fatal(err)
	}
	if !result.UpToDate() || result.Files == 0 {
		t.Fatalf("want up to date with files, got %+v", result)
	}
	// proto, 5 go-server files, 4 csharp-client files, 1 unity bridge.
	if result.Files != 11 {
		t.Fatalf("files = %d, want 11", result.Files)
	}
	requireEmptyDir(t, tmp)
}

func TestCheckReportsDrift(t *testing.T) {
	dir := checkFixture(t)
	tmp := isolateTemp(t)
	writeConsumerFile(t, dir, "generated/actor_synced.go", "// GENERATED by Golem Engine — do not edit.\npackage generated\n")
	if err := os.Remove(filepath.Join(dir, "generated/entities_pb.go")); err != nil {
		t.Fatal(err)
	}
	if err := os.Remove(filepath.Join(dir, "proto/entities.proto")); err != nil {
		t.Fatal(err)
	}
	writeConsumerFile(t, dir, "csharp/RetiredView.cs", "// GENERATED by Golem Engine - edit as needed.\n")
	writeConsumerFile(t, dir, "csharp/Authored.cs", "// hand-written\n")
	writeConsumerFile(t, dir, "generated/nested/old_synced.go", "// GENERATED by Golem Engine — do not edit.\n")

	result, err := checkUnchanged(t, dir)
	if err != nil {
		t.Fatal(err)
	}
	want := []Drift{
		{DriftUnexpected, "csharp/RetiredView.cs"},
		{DriftStale, "generated/actor_synced.go"},
		{DriftMissing, "generated/entities_pb.go"},
		{DriftMissing, "proto/entities.proto"},
	}
	if !reflect.DeepEqual(result.Drift, want) {
		t.Fatalf("drift = %v, want %v", result.Drift, want)
	}
	requireEmptyDir(t, tmp)
}

func TestCheckReportsSchemaChangesWithoutRebake(t *testing.T) {
	dir := checkFixture(t)
	writeConsumerFile(t, dir, "entities/actor.yaml", "entity: Actor\nvars:\n  hp: {tag: 1, type: int32, sync: tick}\n  bag: {tag: 2, type: list<Item>, sync: tick}\n  speed: {tag: 3, type: float, sync: tick}\n")
	writeConsumerFile(t, dir, "entities/crate.yaml", "entity: Crate\nvars:\n  open: {tag: 1, type: bool, sync: tick}\n")
	result, err := checkUnchanged(t, dir)
	if err != nil {
		t.Fatal(err)
	}
	got := map[Drift]bool{}
	for _, d := range result.Drift {
		got[d] = true
	}
	for _, d := range []Drift{
		{DriftStale, "proto/entities.proto"},
		{DriftStale, "generated/actor_synced.go"},
		{DriftStale, "generated/entities_pb.go"},
		{DriftStale, "csharp/SyncedActor.cs"},
		{DriftMissing, "generated/crate_synced.go"},
		{DriftMissing, "csharp/CrateView.cs"},
	} {
		if !got[d] {
			t.Errorf("missing drift %v in %v", d, result.Drift)
		}
	}
	if err := Bake(dir); err != nil {
		t.Fatal(err)
	}
	if result, err := Check(dir); err != nil || !result.UpToDate() {
		t.Fatalf("after rebake: %+v %v", result, err)
	}
}

func TestCheckIgnoresCRLFCheckouts(t *testing.T) {
	dir := checkFixture(t)
	converted := 0
	for _, out := range []string{"generated", "csharp", "proto"} {
		entries, err := os.ReadDir(filepath.Join(dir, out))
		if err != nil {
			t.Fatal(err)
		}
		for _, entry := range entries {
			path := filepath.Join(dir, out, entry.Name())
			b, err := os.ReadFile(path)
			if err != nil {
				t.Fatal(err)
			}
			crlf := strings.ReplaceAll(strings.ReplaceAll(string(b), "\r\n", "\n"), "\n", "\r\n")
			if err := os.WriteFile(path, []byte(crlf), 0o644); err != nil {
				t.Fatal(err)
			}
			converted++
		}
	}
	if converted != 11 {
		t.Fatalf("converted %d files", converted)
	}
	result, err := checkUnchanged(t, dir)
	if err != nil || !result.UpToDate() {
		t.Fatalf("CRLF checkout reported drift: %+v %v", result, err)
	}
	// Content changes are still detected under CRLF.
	path := filepath.Join(dir, "generated", "actor_synced.go")
	b, _ := os.ReadFile(path)
	if err := os.WriteFile(path, append(b, []byte("// edit\r\n")...), 0o644); err != nil {
		t.Fatal(err)
	}
	result, err = checkUnchanged(t, dir)
	if err != nil || !reflect.DeepEqual(result.Drift, []Drift{{DriftStale, "generated/actor_synced.go"}}) {
		t.Fatalf("edited CRLF file: %+v %v", result, err)
	}
}

func TestCheckConfigurationErrorsWriteNothing(t *testing.T) {
	tmp := isolateTemp(t)
	empty := t.TempDir()
	if _, err := checkUnchanged(t, empty); err == nil || !strings.Contains(err.Error(), "golem.yaml") {
		t.Fatalf("missing golem.yaml: %v", err)
	}

	parent := t.TempDir()
	dir := filepath.Join(parent, "game")
	writeConsumerFile(t, dir, "golem.yaml", strings.Replace(checkFixtureConfig, "out: proto/entities.proto", "out: ../escaped.proto", 1))
	writeConsumerFile(t, dir, "entities/actor.yaml", "entity: Actor\nvars:\n  hp: {tag: 1, type: int32, sync: tick}\n")
	if _, err := checkUnchanged(t, dir); err == nil || !strings.Contains(err.Error(), "outside the project") {
		t.Fatalf("escaping proto.out: %v", err)
	}
	if _, err := os.Stat(filepath.Join(parent, "escaped.proto")); !os.IsNotExist(err) {
		t.Fatalf("escaping output was written: %v", err)
	}

	broken := checkFixture(t)
	writeConsumerFile(t, broken, "entities/actor.yaml", "entity: Actor\nvars:\n  hp: [unclosed\n")
	if _, err := checkUnchanged(t, broken); err == nil {
		t.Fatal("invalid schema accepted")
	}
	requireEmptyDir(t, tmp)

	// A temporary directory inside the project is refused before anything is created.
	inside := checkFixture(t)
	nested := filepath.Join(inside, "tmp")
	if err := os.Mkdir(nested, 0o755); err != nil {
		t.Fatal(err)
	}
	for _, key := range []string{"TMPDIR", "TMP", "TEMP"} {
		t.Setenv(key, nested)
	}
	if _, err := checkUnchanged(t, inside); err == nil || !strings.Contains(err.Error(), "inside the project") {
		t.Fatalf("temporary directory inside project: %v", err)
	}
}

// TestCheckJSClientMirrorsModuleResolution bakes a js-client project whose
// node_modules sits above the output directory, then checks that the scratch
// compile resolves the same packages and emits identical JS/declarations.
func TestCheckJSClientMirrorsModuleResolution(t *testing.T) {
	engine, err := filepath.Abs("..")
	if err != nil {
		t.Fatal(err)
	}
	typescript := filepath.Join(engine, "golem-js", "node_modules", "typescript")
	runtime := filepath.Join(engine, "golem-js", "dist", "index.d.ts")
	for _, file := range []string{filepath.Join(typescript, "lib", "tsc.js"), runtime} {
		if _, err := os.Stat(file); err != nil {
			if os.Getenv("GOLEM_REQUIRE_CONSUMERS") == "1" {
				t.Fatal(err)
			}
			t.Skip("build golem-js and install its dependencies first")
		}
	}
	if _, err := exec.LookPath("node"); err != nil {
		if os.Getenv("GOLEM_REQUIRE_CONSUMERS") == "1" {
			t.Fatal(err)
		}
		t.Skip("Node.js required")
	}

	dir := t.TempDir()
	copyTree(t, filepath.Join(engine, "golem-js", "dist"), filepath.Join(dir, "node_modules", "golem-engine", "dist"), nil)
	copyTree(t, filepath.Join(engine, "golem-js", "package.json"), filepath.Join(dir, "node_modules", "golem-engine", "package.json"), nil)
	copyTree(t, filepath.Join(typescript, "package.json"), filepath.Join(dir, "node_modules", "typescript", "package.json"), nil)
	copyTree(t, filepath.Join(typescript, "lib"), filepath.Join(dir, "node_modules", "typescript", "lib"), func(name string) bool {
		return name == "tsc.js" || name == "_tsc.js" || strings.HasPrefix(name, "lib.") && strings.HasSuffix(name, ".d.ts")
	})
	writeConsumerFile(t, dir, "golem.yaml", `entity_schema: entities
command_schema: commands
event_schema: events
proto:
  package: fixture
  out: entities.proto
integrations:
  js-client:
    out: web/src/generated
`)
	writeConsumerFile(t, dir, "entities/actor.yaml", "entity: Actor\nvars:\n  hp: {tag: 1, type: int32, sync: tick}\n")
	writeConsumerFile(t, dir, "commands/move.yaml", "command: Move\ntarget: entity\nentity_type: Actor\nfields:\n  speed: float\n")
	writeConsumerFile(t, dir, "events/notice.yaml", "event: Notice\ntarget: global\nfields:\n  message: string\n")
	if err := Bake(dir); err != nil {
		t.Fatal(err)
	}
	tmp := isolateTemp(t)
	result, err := checkUnchanged(t, dir)
	if err != nil {
		t.Fatal(err)
	}
	if !result.UpToDate() {
		t.Fatalf("js-client drift right after bake: %v", result.Drift)
	}
	if _, err := os.Stat(filepath.Join(dir, "web/src/generated/client.d.ts")); err != nil {
		t.Fatal("fixture did not compile declarations", err)
	}
	if err := os.Remove(filepath.Join(dir, "web/src/generated/client.js")); err != nil {
		t.Fatal(err)
	}
	result, err = checkUnchanged(t, dir)
	if err != nil || !reflect.DeepEqual(result.Drift, []Drift{{DriftMissing, "web/src/generated/client.js"}}) {
		t.Fatalf("removed client.js: %+v %v", result, err)
	}
	requireEmptyDir(t, tmp)
}

func TestMirroredJSBakeTSConfigUsesVisibleNodeModules(t *testing.T) {
	dir := t.TempDir()
	for _, d := range []string{"node_modules/@types", "app/node_modules", "app/src/out"} {
		if err := os.MkdirAll(filepath.Join(dir, d), 0o755); err != nil {
			t.Fatal(err)
		}
	}
	config, err := mirroredJSBakeTSConfig(filepath.Join(dir, "app", "src", "out"))
	if err != nil {
		t.Fatal(err)
	}
	text := string(config)
	nearest := filepath.ToSlash(filepath.Join(dir, "app", "node_modules")) + "/*"
	outer := filepath.ToSlash(filepath.Join(dir, "node_modules")) + "/*"
	types := filepath.ToSlash(filepath.Join(dir, "node_modules", "@types"))
	if i, j := strings.Index(text, nearest), strings.Index(text, outer); i < 0 || j < 0 || i > j {
		t.Fatalf("paths must list nearest node_modules first:\n%s", text)
	}
	for _, want := range []string{`"rootDir": "."`, types, `"strict": true`, `"./**/*.ts"`} {
		if !strings.Contains(text, want) {
			t.Fatalf("missing %s in\n%s", want, text)
		}
	}
	if strings.Contains(text, filepath.ToSlash(filepath.Join(dir, "app", "node_modules", "@types"))) {
		t.Fatalf("nonexistent @types root listed:\n%s", text)
	}
}

// copyTree copies a file or directory tree; keep filters top-level file names.
func copyTree(t *testing.T, src, dst string, keep func(string) bool) {
	t.Helper()
	info, err := os.Stat(src)
	if err != nil {
		t.Fatal(err)
	}
	if !info.IsDir() {
		b, err := os.ReadFile(src)
		if err != nil {
			t.Fatal(err)
		}
		if err := os.MkdirAll(filepath.Dir(dst), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(dst, b, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	entries, err := os.ReadDir(src)
	if err != nil {
		t.Fatal(err)
	}
	for _, entry := range entries {
		if keep != nil && (entry.IsDir() || !keep(entry.Name())) {
			continue
		}
		copyTree(t, filepath.Join(src, entry.Name()), filepath.Join(dst, entry.Name()), nil)
	}
}
