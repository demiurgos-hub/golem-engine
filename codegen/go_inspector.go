// generateGoServerExtra writes the go-server codec plus the inspector schema
// descriptor; the descriptor needs the resolved envelope layout from proto.
func generateGoServerExtra(outDir, golemImport, goPackage string, entities []schema.EntityData, commands []schema.CommandData, worldTypes []schema.WorldTypeData, events []schema.EventData, proto schema.ProtoTemplateData) error {
	if err := generateGoProto(outDir, golemImport, goPackage, entities, commands, worldTypes, events, proto); err != nil {
		return err
	}
	return generateGoInspectorSchema(outDir, golemImport, goPackage, entities, proto)
}

func generateGoInspectorSchema(outDir, golemImport, goPackage string, entities []schema.EntityData, proto schema.ProtoTemplateData) error {
	s, err := buildInspectorSchema(entities, proto)
	if err != nil {
		return err
	}
	src := renderInspectorSchema(golemImport, goPackage, s)
	outPath := filepath.Join(outDir, codecOutputName("go-server", inspectorSchemaOutput))
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(outPath, []byte(src), 0o644); err != nil {
		return fmt.Errorf("writing %s: %w", outPath, err)
	}
	if err := gofmtFile(outPath); err != nil {
		return err
	}
	logf("  wrote %s\n", outPath)
	return nil
}

// buildInspectorSchema resolves the inspector descriptor from the same wire
// layout and envelope allocation the codec generators use, so the tags and
// dirty bits always match the generated encoders.
func buildInspectorSchema(entities []schema.EntityData, proto schema.ProtoTemplateData) (*wire.Schema, error) {
	dims := proto.Dimensions
	if dims == 0 {
		dims = 2
	}
	custom := map[string]bool{}
	for _, ct := range proto.CustomTypes {
		custom[ct.Name] = true
	}
	layout := proto.EnvelopeLayouts().Entity
	s := &wire.Schema{Fingerprint: ComputeSchemaFingerprint(entities), Dimensions: uint32(dims)}
	for _, v := range layout.Variants {
		if v.Role == "removal" || v.MessageType == "EntityRemoved" {
			s.RemovedTag = uint32(v.Tag)
		}
	}
	for _, ed := range entities {
		stateTag, deltaTag := envelopeTags(layout, ed.Name)
		if stateTag == 0 || deltaTag == 0 {
			return nil, fmt.Errorf("inspector schema: entity %q has no EntityUpdate tags", ed.Name)
		}
		wl := ed.ProtoWireLayout(dims)
		bits := map[string]int32{}
		for _, f := range wl.Delta {
			if f.Role == "position" || f.Role == "variable" {
				bits[f.SnakeName] = int32(f.BitIndex)
			}
		}
		e := wire.Entity{Name: ed.Name, StateTag: uint32(stateTag), DeltaTag: uint32(deltaTag), Global: ed.Global, Is3D: ed.Is3D}
		for _, f := range wl.State {
			bit, ok := bits[f.SnakeName]
			if !ok {
				bit = -1
			}
			field := wire.Field{Name: f.SnakeName, Tag: uint32(f.ProtoTag), Bit: bit, Sync: f.Sync, OwnerOnly: f.OwnerOnly, Role: f.Role, Type: f.ProtoType}
			switch {
			case f.IsRepeated:
				field.Kind, field.Type = wire.KindList, f.ElemProtoType
			case f.IsMap:
				field.Kind, field.Type, field.KeyType = wire.KindMap, f.ElemProtoType, f.MapKeyProtoType
			case custom[f.ProtoType]:
				field.Kind = wire.KindCustom
			}
			if f.Role != "variable" {
				field.Sync = ""
			}
			e.Fields = append(e.Fields, field)
		}
		s.Entities = append(s.Entities, e)
	}
	for _, ct := range proto.CustomTypes {
		t := wire.CustomType{Name: ct.Name}
		for _, f := range ct.Fields {
			field := wire.Field{Name: f.SnakeName, Tag: uint32(f.ProtoTag), Bit: -1, Type: f.ProtoType}
			if custom[f.ProtoType] {
				field.Kind = wire.KindCustom
			}
			t.Fields = append(t.Fields, field)
		}
		s.Types = append(s.Types, t)
	}
	if err := s.Validate(); err != nil {
		return nil, fmt.Errorf("inspector schema: %w", err)
	}
	return s, nil
}

func envelopeTags(layout schema.EnvelopeLayout, entity string) (state, delta int) {
	for _, v := range layout.Variants {
		isState := v.Role == "state" && v.Declaration == entity || v.Role == "" && v.MessageType == entity+"State"
		isDelta := v.Role == "delta" && v.Declaration == entity || v.Role == "" && v.MessageType == entity+"Delta"
		if isState {
			state = v.Tag
		} else if isDelta {
			delta = v.Tag
		}
	}
	return state, delta
}

func renderInspectorSchema(golemImport, goPackage string, s *wire.Schema) string {
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format+"\n", args...) }
	w("// GENERATED by Golem Engine — do not edit.")
	w("package %s", goPackage)
	w("")
	w("import \"%s/inspector/wire\"", golemImport)
	w("")
	w("// InspectorSchema describes this project's entity wire layout for the Golem")
	w("// Inspector. Pass it to inspector.Attach; each call returns a fresh copy.")
	w("func InspectorSchema() *wire.Schema {")
	w("\treturn &wire.Schema{")
	w("\t\tFingerprint: %q,", s.Fingerprint)
	w("\t\tDimensions: %d,", s.Dimensions)
	w("\t\tRemovedTag: %d,", s.RemovedTag)
	w("\t\tEntities: []wire.Entity{")
	for _, e := range s.Entities {
		w("\t\t\t{Name: %q, StateTag: %d, DeltaTag: %d, Global: %t, Is3D: %t, Fields: []wire.Field{", e.Name, e.StateTag, e.DeltaTag, e.Global, e.Is3D)
		for _, f := range e.Fields {
			w("\t\t\t\t%s,", renderInspectorField(f))
		}
		w("\t\t\t}},")
	}
	w("\t\t},")
	if len(s.Types) > 0 {
		w("\t\tTypes: []wire.CustomType{")
		for _, t := range s.Types {
			w("\t\t\t{Name: %q, Fields: []wire.Field{", t.Name)
			for _, f := range t.Fields {
				w("\t\t\t\t%s,", renderInspectorField(f))
			}
			w("\t\t\t}},")
		}
		w("\t\t},")
	}
	w("\t}")
	w("}")
	return b.String()
}

var inspectorKindNames = map[wire.FieldKind]string{
	wire.KindScalar: "wire.KindScalar", wire.KindCustom: "wire.KindCustom",
	wire.KindList: "wire.KindList", wire.KindMap: "wire.KindMap",
}

func renderInspectorField(f wire.Field) string {
	parts := []string{fmt.Sprintf("Name: %q", f.Name), fmt.Sprintf("Tag: %d", f.Tag), fmt.Sprintf("Bit: %d", f.Bit)}
	if f.Sync != "" {
		parts = append(parts, fmt.Sprintf("Sync: %q", f.Sync))
	}
	if f.OwnerOnly {
		parts = append(parts, "OwnerOnly: true")
	}
	if f.Kind != wire.KindScalar {
		parts = append(parts, "Kind: "+inspectorKindNames[f.Kind])
	}
	parts = append(parts, fmt.Sprintf("Type: %q", f.Type))
	if f.KeyType != "" {
		parts = append(parts, fmt.Sprintf("KeyType: %q", f.KeyType))
	}
	if f.Role != "" {
		parts = append(parts, fmt.Sprintf("Role: %q", f.Role))
	}
	return "{" + strings.Join(parts, ", ") + "}"
}
