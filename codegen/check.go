package codegen

import (
	"bytes"
	"fmt"
	"io"
	"io/fs"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/demiurgos-hub/golem-engine/schema"
)

// generatedHeader prefixes every file Golem Engine owns in an integration
// output directory (except finalized JSON bundles and protobuf schemas).
const generatedHeader = "// GENERATED by Golem Engine"

// DriftKind classifies one difference between generated and committed output.
type DriftKind string

const (
	// DriftMissing marks a file a bake would write that does not exist.
	DriftMissing DriftKind = "missing"
	// DriftStale marks a file whose content differs from what a bake would write.
	DriftStale DriftKind = "stale"
	// DriftUnexpected marks a top-level file in an integration output directory
	// that carries the Golem generated header but that a bake would not write.
	DriftUnexpected DriftKind = "unexpected"
)

// Drift is one generated path that differs from a fresh bake.
type Drift struct {
	Kind DriftKind
	Path string // slash-separated, relative to the project root
}

// CheckResult reports how a project's generated files compare with a fresh bake.
type CheckResult struct {
	Files int     // files a bake would write
	Drift []Drift // sorted by path; empty when up to date
}

// UpToDate reports whether the project's generated files match a fresh bake.
func (r CheckResult) UpToDate() bool { return len(r.Drift) == 0 }

// Check runs the same generation as Bake (same templates, gofmt and TypeScript
// toolchain), but writes into a temporary directory and compares the result
// with the project instead of modifying it. Text is compared after converting
// CRLF to LF on both sides. Every configured output path must stay inside the
// project. The temporary directory is removed before Check returns; the project
// is never written, even when generation fails.
func Check(projectRoot string) (CheckResult, error) {
	root, err := filepath.Abs(projectRoot)
	if err != nil {
		return CheckResult{}, err
	}

	// The scratch tree is created only once inputs are valid: a schema error
	// that exits through log.Fatal must not leave a directory behind.
	var cfg *schema.Config
	var scratch string
	defer func() {
		if scratch != "" {
			os.RemoveAll(scratch)
		}
	}()
	output := func(loaded *schema.Config) (string, error) {
		if err := requireContainedOutputs(root, loaded); err != nil {
			return "", err
		}
		tmp, err := filepath.Abs(os.TempDir())
		if err != nil {
			return "", err
		}
		if rel, err := filepath.Rel(root, tmp); err == nil && isContainedRelativePath(rel) {
			return "", fmt.Errorf("temporary directory %s is inside the project; point TMPDIR/TEMP elsewhere", tmp)
		}
		dir, err := os.MkdirTemp(tmp, "golem-bake-check-")
		if err != nil {
			return "", err
		}
		scratch, cfg = dir, loaded
		return dir, nil
	}

	bakeMu.Lock()
	previous := bakeLog
	bakeLog = io.Discard
	err = bake(root, output)
	bakeLog = previous
	bakeMu.Unlock()
	if err != nil {
		return CheckResult{}, err
	}
	return compareGenerated(root, scratch, cfg)
}

// requireContainedOutputs rejects outputs that a mirrored bake could not place
// under its scratch root without writing elsewhere.
func requireContainedOutputs(projectRoot string, cfg *schema.Config) error {
	check := func(what, out string) error {
		rel, err := filepath.Rel(projectRoot, filepath.Join(projectRoot, out))
		if err != nil || !isContainedRelativePath(rel) {
			return fmt.Errorf("%s %q resolves outside the project; check only verifies outputs inside the project", what, out)
		}
		return nil
	}
	if err := check("proto.out", cfg.Proto.Out); err != nil {
		return err
	}
	for _, name := range sortedIntegrationNames(cfg) {
		if err := check("integrations."+name+".out", cfg.Integrations[name].Out); err != nil {
			return err
		}
	}
	return nil
}

func sortedIntegrationNames(cfg *schema.Config) []string {
	names := make([]string, 0, len(cfg.Integrations))
	for name := range cfg.Integrations {
		names = append(names, name)
	}
	sort.Strings(names)
	return names
}

func compareGenerated(root, scratch string, cfg *schema.Config) (CheckResult, error) {
	var result CheckResult
	produced := map[string]bool{}
	err := filepath.WalkDir(scratch, func(path string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		rel, err := filepath.Rel(scratch, path)
		if err != nil {
			return err
		}
		produced[rel] = true
		result.Files++
		want, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		target := filepath.Join(root, rel)
		info, err := os.Stat(target)
		if os.IsNotExist(err) {
			result.Drift = append(result.Drift, Drift{DriftMissing, filepath.ToSlash(rel)})
			return nil
		}
		if err != nil {
			return err
		}
		if !info.Mode().IsRegular() {
			result.Drift = append(result.Drift, Drift{DriftStale, filepath.ToSlash(rel)})
			return nil
		}
		got, err := os.ReadFile(target)
		if err != nil {
			return err
		}
		if !sameGenerated(want, got) {
			result.Drift = append(result.Drift, Drift{DriftStale, filepath.ToSlash(rel)})
		}
		return nil
	})
	if err != nil {
		return CheckResult{}, err
	}

	// Generated outputs are top-level files of their integration directory;
	// directories shared by several integrations are scanned once against the
	// union of their outputs.
	scanned := map[string]bool{}
	for _, name := range sortedIntegrationNames(cfg) {
		out := filepath.Clean(cfg.Integrations[name].Out)
		if scanned[out] {
			continue
		}
		scanned[out] = true
		entries, err := os.ReadDir(filepath.Join(root, out))
		if os.IsNotExist(err) {
			continue
		}
		if err != nil {
			return CheckResult{}, err
		}
		for _, entry := range entries {
			rel := filepath.Join(out, entry.Name())
			if !entry.Type().IsRegular() || produced[rel] {
				continue
			}
			owned, err := hasGeneratedHeader(filepath.Join(root, rel))
			if err != nil {
				return CheckResult{}, err
			}
			if owned {
				result.Drift = append(result.Drift, Drift{DriftUnexpected, filepath.ToSlash(rel)})
			}
		}
	}
	sort.Slice(result.Drift, func(i, j int) bool { return result.Drift[i].Path < result.Drift[j].Path })
	return result, nil
}

// sameGenerated compares text with CRLF normalised to LF so Git checkouts with
// autocrlf are not reported stale; content with NUL bytes is compared exactly.
func sameGenerated(want, got []byte) bool {
	if bytes.IndexByte(want, 0) >= 0 || bytes.IndexByte(got, 0) >= 0 {
		return bytes.Equal(want, got)
	}
	crlf, lf := []byte("\r\n"), []byte("\n")
	return bytes.Equal(bytes.ReplaceAll(want, crlf, lf), bytes.ReplaceAll(got, crlf, lf))
}

func hasGeneratedHeader(path string) (bool, error) {
	f, err := os.Open(path)
	if err != nil {
		return false, err
	}
	defer f.Close()
	head := make([]byte, len(generatedHeader))
	n, err := io.ReadFull(f, head)
	if err != nil && err != io.ErrUnexpectedEOF && err != io.EOF {
		return false, err
	}
	return strings.HasPrefix(string(head[:n]), generatedHeader), nil
}
