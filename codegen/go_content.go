func renderGoContent(data *schema.ContentData, pkg string, proto schema.ProtoTemplateData) ([]byte, error) {
	if err := validateGoContentNames(data.Schema, proto); err != nil {
		return nil, err
	}
	types := append([]content.Type(nil), data.Schema.Types...)
	sort.Slice(types, func(i, j int) bool { return types[i].Name < types[j].Name })
	byName := make(map[string]content.Type, len(types))
	for _, typ := range types {
		byName[typ.Name] = typ
	}
	var b strings.Builder
	w := func(f string, args ...any) { fmt.Fprintf(&b, f+"\n", args...) }
	w("// GENERATED by Golem Engine — do not edit.")
	w("package %s", pkg)
	// A custom golem_import may be a thin consumer runtime facade, not a package tree.
	w("import (\"encoding/json\"; \"io\"; \"strings\"; content %q)", "github.com/demiurgos-hub/golem-engine/golem/content")
	w("// ContentSchemaHash identifies the portable definition schema, independently of wire state.")
	w("const ContentSchemaHash = %q", data.SchemaHash)
	w("const contentSchemaJSON = %q", string(data.SchemaJSON))
	w("// Definitions owns immutable typed definitions and their resolved references.")
	w("type Definitions struct {")
	w("catalog *content.Catalog")
	for _, typ := range types {
		if typ.Definition {
			w("by%s map[string]%s", contentName(typ.Name), contentTypeName(typ.Name))
		}
	}
	w("}")
	w("// LoadDefinitions validates a finalized content bundle and creates immutable typed access.")
	w("// options.Imports supplies explicitly declared dependencies; schema identity is always required.")
	w("func LoadDefinitions(reader io.Reader, options content.Options) (*Definitions, error) {")
	w("s, err := content.ParseSchema(strings.NewReader(contentSchemaJSON)); if err != nil { return nil, err }")
	w("options.RequireSchemaHash = true")
	w("catalog, err := content.Load(reader, s, options); if err != nil { return nil, err }")
	w("result := &Definitions{catalog: catalog}")
	for _, typ := range types {
		if typ.Definition {
			name := contentName(typ.Name)
			w("result.by%s = make(map[string]%s)", name, contentTypeName(typ.Name))
			w("for _, view := range catalog.All(%q) { result.by%s[view.ID()] = new%s(view, result) }", typ.Name, name, contentTypeName(typ.Name))
		}
	}
	w("return result, nil")
	w("}")
	w("// Hash returns the normalized content identity, including declared imports.")
	w("func (d *Definitions) Hash() string { if d == nil { return \"\" }; return d.catalog.Hash() }")
	w("// Catalog returns the immutable catalog, for example when loading an importing bundle.")
	w("func (d *Definitions) Catalog() *content.Catalog { if d == nil { return nil }; return d.catalog }")
	for _, typ := range types {
		if typ.Definition {
			name, native := contentName(typ.Name), contentTypeName(typ.Name)
			w("// Lookup%s finds a definition by its stable content identity.", name)
			w("func (d *Definitions) Lookup%s(id string) (%s, bool) { if d == nil { return %s{}, false }; value, ok := d.by%s[id]; return value, ok }", name, native, native, name)
			w("// All%s returns independently owned views ordered by stable content identity.", name)
			w("func (d *Definitions) All%s() []%s { if d == nil { return nil }; views := d.catalog.All(%q); result := make([]%s, len(views)); for i, view := range views { result[i] = d.by%s[view.ID()] }; return result }", name, native, typ.Name, native, name)
		}
		switch typ.Kind {
		case "enum", "flags":
			writeGoContentEnum(w, typ)
		default:
			writeGoContentRecord(w, typ, byName)
		}
	}
	// These helpers only decode values already validated by content.Load. A decode
	// failure therefore identifies a generator/runtime contract bug, not bad input.
	w("func contentDecode[T any](raw json.RawMessage) T { var value T; if len(raw) == 0 || string(raw) == \"null\" { return value }; if err := json.Unmarshal(raw, &value); err != nil { panic(\"validated content decode: \" + err.Error()) }; return value }")
	w("func contentList[T any](raw json.RawMessage, decode func(json.RawMessage) T) []T { values := contentDecode[[]json.RawMessage](raw); result := make([]T, len(values)); for i, value := range values { result[i] = decode(value) }; return result }")
	w("func contentMapList[A, B any](values []A, convert func(A) B) []B { result := make([]B, len(values)); for i, value := range values { result[i] = convert(value) }; return result }")
	w("func contentPresent(raw json.RawMessage) bool { return len(raw) != 0 && strings.TrimSpace(string(raw)) != \"null\" }")
	result, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("generating content definitions: %w", err)
	}
	return result, nil
}

func writeGoContentEnum(w func(string, ...any), typ content.Type) {
	name := contentTypeName(typ.Name)
	valueName := name
	if typ.Kind == "flags" {
		valueName += "Value"
	}
	w("// %s is an authored %s value.", valueName, typ.Kind)
	w("type %s string", valueName)
	for _, value := range typ.Values {
		constant := name + contentName(value)
		w("// %s names the %q value.", constant, value)
		w("const %s %s = %q", constant, valueName, value)
	}
	if typ.Kind == "flags" {
		w("// %s is an immutable set of authored flags.", name)
		w("type %s struct { values []%s }", name, valueName)
		w("// Values returns an independently owned list of flags.")
		w("func (v %s) Values() []%s { result := make([]%s, len(v.values)); copy(result, v.values); return result }", name, valueName, valueName)
		w("// Has reports whether the specified flag is present.")
		w("func (v %s) Has(flag %s) bool { for _, value := range v.values { if value == flag { return true } }; return false }", name, valueName)
	}
}

func writeGoContentRecord(w func(string, ...any), typ content.Type, types map[string]content.Type) {
	name := contentTypeName(typ.Name)
	w("// %s exposes immutable %s configuration.", name, typ.Name)
	w("type %s struct {", name)
	w("definitions *Definitions")
	if typ.Definition {
		w("view content.View")
	}
	for i, field := range typ.Fields {
		w("f%d %s", i, contentGoType(field.Type, false))
		if field.Optional {
			w("hasF%d bool", i)
		}
	}
	w("}")
	if typ.Definition {
		w("func new%s(view content.View, definitions *Definitions) %s {", name, name)
		w("fields := map[string]json.RawMessage{}")
		for _, field := range typ.Fields {
			w("fields[%q] = view.Raw(%q)", field.Name, field.Name)
		}
	} else {
		w("func new%s(raw json.RawMessage, definitions *Definitions) %s {", name, name)
		w("fields := contentDecode[map[string]json.RawMessage](raw)")
	}
	w("_ = fields")
	w("return %s{definitions: definitions,", name)
	if typ.Definition {
		w("view: view,")
	}
	for i, field := range typ.Fields {
		raw := fmt.Sprintf("fields[%q]", field.Name)
		w("f%d: %s,", i, contentDecodeExpr(field.Type, raw, "definitions", types))
		if field.Optional {
			w("hasF%d: contentPresent(%s),", i, raw)
		}
	}
	w("}")
	w("}")
	if typ.Definition {
		w("// ID returns the stable content identity, not a live entity ID.")
		w("func (v %s) ID() string { return v.view.ID() }", name)
		w("// Factory returns the consumer-owned behavior or factory key.")
		w("func (v %s) Factory() string { return v.view.Factory() }", name)
	}
	for i, field := range typ.Fields {
		method := contentName(field.Name)
		result := contentGoType(field.Type, true)
		expr := contentReadExpr(field.Type, fmt.Sprintf("v.f%d", i), "v.definitions")
		if field.Optional {
			w("// %s returns the configured value and whether it is present.", method)
			w("func (v %s) %s() (%s, bool) { return %s, v.hasF%d }", name, method, result, expr, i)
		} else {
			w("// %s returns the immutable configured value.", method)
			w("func (v %s) %s() %s { return %s }", name, method, result, expr)
		}
	}
}

func contentName(name string) string     { return schema.SnakeToPascal(name) }
func contentTypeName(name string) string { return "Content" + contentName(name) }

func contentGoType(typ string, public bool) string {
	if strings.HasPrefix(typ, "[]") {
		return "[]" + contentGoType(strings.TrimPrefix(typ, "[]"), public)
	}
	if strings.HasPrefix(typ, "ref:") {
		if public {
			return contentTypeName(strings.TrimPrefix(typ, "ref:"))
		}
		return "string"
	}
	switch typ {
	case "bool", "string", "int32", "uint32", "int64", "uint64", "float32", "float64":
		return typ
	default:
		return contentTypeName(typ)
	}
}

func contentDecodeExpr(typ, raw, definitions string, types map[string]content.Type) string {
	if strings.HasPrefix(typ, "[]") {
		elem := strings.TrimPrefix(typ, "[]")
		return fmt.Sprintf("contentList(%s, func(raw json.RawMessage) %s { return %s })", raw, contentGoType(elem, false), contentDecodeExpr(elem, "raw", definitions, types))
	}
	if named, ok := types[typ]; ok {
		switch named.Kind {
		case "flags":
			return fmt.Sprintf("%s{values: contentDecode[[]%sValue](%s)}", contentTypeName(typ), contentTypeName(typ), raw)
		case "enum":
		default:
			return fmt.Sprintf("new%s(%s, %s)", contentTypeName(typ), raw, definitions)
		}
	}
	return fmt.Sprintf("contentDecode[%s](%s)", contentGoType(typ, false), raw)
}

func contentReadExpr(typ, value, definitions string) string {
	if strings.HasPrefix(typ, "[]") {
		elem := strings.TrimPrefix(typ, "[]")
		return fmt.Sprintf("contentMapList(%s, func(value %s) %s { return %s })", value, contentGoType(elem, false), contentGoType(elem, true), contentReadExpr(elem, "value", definitions))
	}
	if strings.HasPrefix(typ, "ref:") {
		name := strings.TrimPrefix(typ, "ref:")
		return fmt.Sprintf("func() %s { result, _ := %s.Lookup%s(%s); return result }()", contentTypeName(name), definitions, contentName(name), value)
	}
	return value
}

func validateGoContentNames(s content.Schema, proto schema.ProtoTemplateData) error {
	names := map[string]string{}
	claim := func(name, source string) error {
		if !token.IsIdentifier(name) || !ast.IsExported(name) {
			return fmt.Errorf("content %s generates invalid exported Go name %q", source, name)
		}
		if prev, exists := names[name]; exists {
			return fmt.Errorf("content %s generates Go name %q already used by %s", source, name, prev)
		}
		names[name] = source
		return nil
	}
	for _, typ := range proto.CustomTypes {
		names[typ.Name] = "protocol custom type " + typ.Name
	}
	for _, entity := range proto.Entities {
		for _, name := range []string{"Synced" + entity.Name, entity.Name + "State", entity.Name + "Delta"} {
			names[name] = "replicated entity " + entity.Name
		}
	}
	for _, world := range proto.WorldTypes {
		names[world.DataName] = "replicated world type " + world.Name
	}
	for _, command := range proto.Commands {
		names[commandPayload(command).Name] = "command " + command.Name
	}
	for _, event := range proto.Events {
		names[eventPayload(event).Name] = "event " + event.Name
	}
	for _, set := range proto.ProtocolConstantSets {
		for _, member := range set.Members {
			names[set.Name+member.Name] = "protocol constant " + set.SnakeName + "." + member.SnakeName
		}
	}
	for _, name := range []string{"Definitions", "LoadDefinitions", "ContentSchemaHash"} {
		if err := claim(name, "generated helper"); err != nil {
			return err
		}
	}
	for _, typ := range s.Types {
		name := contentTypeName(typ.Name)
		if err := claim(name, "type "+typ.Name); err != nil {
			return err
		}
		if typ.Kind == "flags" {
			if err := claim(name+"Value", "flag "+typ.Name); err != nil {
				return err
			}
		}
		for _, value := range typ.Values {
			if err := claim(name+contentName(value), "value "+typ.Name+"."+value); err != nil {
				return err
			}
		}
		methods := map[string]string{"ID": "identity", "Factory": "factory", "Definitions": "internal storage", "View": "internal storage"}
		for _, field := range typ.Fields {
			method := contentName(field.Name)
			if !token.IsIdentifier(method) || !ast.IsExported(method) {
				return fmt.Errorf("content field %s.%s generates invalid Go method %q", typ.Name, field.Name, method)
			}
			if prev, exists := methods[method]; exists {
				return fmt.Errorf("content field %s.%s generates Go method %q already used by %s", typ.Name, field.Name, method, prev)
			}
			methods[method] = field.Name
		}
	}
	return nil
}
